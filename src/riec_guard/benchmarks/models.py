"""Immutable public models for the fixed synthetic demonstration gallery."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Annotated, Literal

from pydantic import Field, StringConstraints, model_validator

from riec_guard.contract.models import (
    ActionDecision,
    ActionState,
    ProtocolId,
    ProtocolResult,
    ProtocolStatus,
    RiecSelection,
)
from riec_guard.errors import (
    CanonicalModel,
    FiniteNumber,
    ImmutableTuple,
    LimitedString32,
    LimitedString100,
    LimitedString500,
    StrictStrEnum,
    UniqueTuple,
)
from riec_guard.evidence.models import EvidenceLedger

Sha256 = Annotated[str, StringConstraints(pattern=r"^[a-f0-9]{64}$")]
ContractId = Annotated[str, StringConstraints(pattern=r"^AC-[A-F0-9]{12}$")]
EvidenceId = Annotated[
    str,
    StringConstraints(pattern=r"^EV-[A-Z0-9_]{2,16}-[A-F0-9]{12}$"),
]
CandidateId = Annotated[str, StringConstraints(pattern=r"^M[0-9]+_[a-z0-9_]+$")]
ReasonCode = Annotated[str, StringConstraints(pattern=r"^[A-Z][A-Z0-9_]{2,63}$")]


class ScenarioId(StrictStrEnum):
    STABLE_SYMMETRIC = "stable_symmetric"
    HEAVY_TAIL_PARTICULATE = "heavy_tail_particulate"
    BATCH_DRIFT_CHANGE_POINT = "batch_drift_change_point"


class DemoG1State(StrictStrEnum):
    PASS = "pass"
    MATERIAL_WARNING = "material_warning"
    INELIGIBLE = "ineligible"


class PublicClassification(StrictStrEnum):
    PUBLIC_SYNTHETIC = "public_synthetic"


class MechanismParameter(CanonicalModel):
    name: LimitedString100
    value: FiniteNumber
    unit: LimitedString32 | None


class ScenarioExpectation(CanonicalModel):
    g1_state: DemoG1State
    g2_action_supported: Literal[True]
    protocol_conflict: bool
    action_state: ActionState
    positive_pilot_interval: bool
    h2_more_optimistic_than_h1_or_h3: bool


class SharedPolicyProfile(CanonicalModel):
    profile_id: Literal["public-demo-policy.v1"]
    nominal_quantity: FiniteNumber
    lower_limit: FiniteNumber
    alpha: FiniteNumber
    measurement_resolution: FiniteNumber
    minimum_actionable_shift: FiniteNumber
    maximum_screening_shift: FiniteNumber
    protocol_spread_tolerance: FiniteNumber
    unit: Literal["mL"]
    min_expected_tail_count: Literal[5]
    bootstrap_replicates: Literal[200]
    bootstrap_seed: Literal[20260718]

    @model_validator(mode="after")
    def _validate_frozen_values(self) -> SharedPolicyProfile:
        observed = (
            self.nominal_quantity,
            self.lower_limit,
            self.alpha,
            self.measurement_resolution,
            self.minimum_actionable_shift,
            self.maximum_screening_shift,
            self.protocol_spread_tolerance,
        )
        if observed != (250.0, 249.5, 0.01, 0.01, 0.05, 0.5, 0.5):
            raise ValueError("public demo policy values are frozen")
        return self


class SharedScenarioDesign(CanonicalModel):
    deployment_group_count: Literal[12]
    product_count: Literal[2]
    stream_count: Literal[2]
    shift_count: Literal[2]
    replicates_per_cell: Literal[11]
    rows_per_group: Literal[88]
    row_count: Literal[1056]
    rows_per_product: Literal[528]
    expected_tail_count_per_product: FiniteNumber

    @model_validator(mode="after")
    def _validate_tail_support(self) -> SharedScenarioDesign:
        if self.expected_tail_count_per_product != 5.28:
            raise ValueError("public demo expected product-tail support is frozen")
        return self


class ScenarioDefinition(CanonicalModel):
    scenario_id: ScenarioId
    scenario_version: Literal["1.0.0"]
    display_name: LimitedString100
    mechanism_description: LimitedString500
    domain_hint: LimitedString100
    seed: Annotated[int, Field(ge=0, le=2**32 - 1)]
    csv_asset: Annotated[
        str,
        StringConstraints(pattern=r"^data/public_synthetic/[a-z0-9_]+\.csv$"),
    ]
    classification: Literal[PublicClassification.PUBLIC_SYNTHETIC]
    design: SharedScenarioDesign
    policy: SharedPolicyProfile
    mechanism_parameters: Annotated[
        ImmutableTuple[MechanismParameter],
        Field(min_length=1, max_length=20),
    ]
    expectation: ScenarioExpectation
    limitation: LimitedString500


@dataclass(frozen=True, slots=True)
class GeneratedScenario:
    """Generated bytes stay internal and are never part of a public result."""

    definition: ScenarioDefinition
    csv_bytes: bytes
    dataset_sha256: str


class ScenarioCatalog(CanonicalModel):
    schema_version: Literal["1.0.0"]
    catalog_id: Literal["riec-guard-public-scenarios.v1"]
    catalog_version: Literal["1.0.0"]
    fixed_order: Annotated[ImmutableTuple[ScenarioId], Field(min_length=3, max_length=3)]
    shared_design: SharedScenarioDesign
    shared_policy: SharedPolicyProfile
    scenarios: Annotated[ImmutableTuple[ScenarioDefinition], Field(min_length=3, max_length=3)]
    classification: Literal[PublicClassification.PUBLIC_SYNTHETIC]
    purpose: LimitedString500
    limitations: Annotated[UniqueTuple[LimitedString500], Field(min_length=3, max_length=8)]
    content_sha256: Sha256


class ProtocolDisplay(CanonicalModel):
    protocol_id: ProtocolId
    status: ProtocolStatus
    value: FiniteNumber | None
    lower_bound: FiniteNumber | None
    unit: LimitedString32 | None


class BootstrapDisplay(CanonicalModel):
    protocol_id: Literal[ProtocolId.U1_GROUP_BOOTSTRAP_BOUND]
    status: ProtocolStatus
    lower_bound: FiniteNumber | None
    requested_replicates: Literal[200]
    successful_replicates: Annotated[int, Field(ge=0, le=200)]
    failed_replicates: Annotated[int, Field(ge=0, le=200)]
    seed: Literal[20260718]


class SufficiencyDisplay(CanonicalModel):
    protocol_id: Literal[ProtocolId.G2_EVIDENCE_SUFFICIENCY_GATE]
    status: ProtocolStatus
    action_supported: bool
    minimum_product_rows: Annotated[int, Field(ge=0)]
    minimum_product_groups: Annotated[int, Field(ge=0)]
    alpha: FiniteNumber
    expected_tail_count: FiniteNumber
    min_expected_tail_count: FiniteNumber

    @model_validator(mode="after")
    def _validate_frozen_thresholds(self) -> SufficiencyDisplay:
        if self.alpha != 0.01 or self.min_expected_tail_count != 5.0:
            raise ValueError("recorded sufficiency thresholds are frozen")
        return self


class EvidenceNodeDisplay(CanonicalModel):
    component: Annotated[str, StringConstraints(pattern=r"^(RIEC|PROTOCOL|ACTION)$")]
    evidence_id: EvidenceId
    content_sha256: Sha256
    parent_evidence_ids: UniqueTuple[EvidenceId]


class RecordedScenarioSummary(CanonicalModel):
    scenario_id: ScenarioId
    scenario_version: Literal["1.0.0"]
    dataset_sha256: Sha256
    row_count: Literal[1056]
    deployment_group_count: Literal[12]
    product_count: Literal[2]
    rows_per_product: Literal[528]
    expected_tail_count_per_product: FiniteNumber
    policy_profile_id: Literal["public-demo-policy.v1"]
    contract_id: ContractId
    contract_sha256: Sha256
    riec_winner: CandidateId
    riec_runner_up: CandidateId | None
    riec_near_tie: bool
    equivalence_set: UniqueTuple[CandidateId]
    h1: ProtocolDisplay
    h2: ProtocolDisplay
    h3: ProtocolDisplay
    u1: BootstrapDisplay
    g1_state: DemoG1State
    g2: SufficiencyDisplay
    protocol_spread: FiniteNumber | None
    protocol_conflict: bool
    action_state: ActionState
    decisive_reason: ReasonCode
    pilot_min: FiniteNumber | None
    pilot_max: FiniteNumber | None
    unit: Literal["mL"]
    riec_evidence_id: EvidenceId
    protocol_evidence_id: EvidenceId
    action_evidence_id: EvidenceId
    evidence_chain: Annotated[
        ImmutableTuple[EvidenceNodeDisplay],
        Field(min_length=3, max_length=3),
    ]
    riec_selection_canonical_sha256_normalized_run_id: Sha256
    protocol_result_canonical_sha256_normalized_run_id: Sha256
    action_decision_canonical_sha256_normalized_run_id: Sha256
    record_sha256: Sha256

    @model_validator(mode="after")
    def _validate_recorded_tail_support(self) -> RecordedScenarioSummary:
        if self.expected_tail_count_per_product != 5.28:
            raise ValueError("recorded expected product-tail support is frozen")
        return self


